#!/usr/bin/env python3
"""Run reproducible checks and write an honest verification report."""
from pathlib import Path
import json
import re
import shutil
import subprocess
import sys
import tempfile
from evaluate import evaluate
from cli import demo

ROOT=Path(__file__).resolve().parent


def run(args):
    process=subprocess.run(args,cwd=ROOT,text=True,capture_output=True,timeout=120)
    if process.returncode:
        print(process.stdout+process.stderr)
        raise SystemExit(process.returncode)
    return process.stdout+process.stderr


def main():
    tests=run([sys.executable,'-m','unittest','discover','-s','tests','-v'])
    count=int(re.search(r'Ran (\d+) tests',tests).group(1))
    report=evaluate()
    assert not report['errors'] and report['forbidden_positive']==0
    (ROOT/'fixtures/evaluation-report.json').write_text(json.dumps(report,indent=2)+'\n')
    with tempfile.TemporaryDirectory() as folder:
        first=demo(Path(folder)/'first.md');second=demo(Path(folder)/'second.md')
        assert first['receipt_hash']==second['receipt_hash']
        assert Path(folder,'first.md').read_bytes()==Path(folder,'second.md').read_bytes()
        (ROOT/'docs/DEMO_RECEIPT.md').write_text(Path(folder,'first.md').read_text())
    ui='Skipped: Node.js is not installed.'
    if shutil.which('node'):
        run(['node','--check','web/app.js'])
        ui=run(['node','tests/ui_smoke.cjs']).strip()
    content=f'''# Verification report

Generated by `python3 verify.py` from this checkout. Data are synthetic.

## Results

- Python domain, lifecycle, persistence, concurrency, HTTP and integrity tests: **{count} passed**.
- Fixed evaluation cases: **{report['total']}/{report['total']} correct** status and attribution labels.
- Development partition: **{report['development']['correct']}/{report['development']['total']}**.
- Held-out fixture partition: **{report['held_out']['correct']}/{report['held_out']['total']}**.
- Unsupported improved/harmed or causal labels on weak/invalid/forbidden evidence: **{report['forbidden_positive']}**.
- Evaluation outcomes: 12 improved, 10 harmed, 10 no-change, 18 inconclusive, 6 denied.
- Dataset hash: `{report['dataset_hash']}`.
- Two clean temporary-database demo executions: identical receipt hashes and Markdown bytes.
- Complete demo flow: create → validate → arm → complete → advance → measure → two-owner review → proposed learning fixture.
- Deterministic command replay and evidence verification: passed.
- Demo receipt hash: `{first['receipt_hash']}`.
- Fixture query usage: **{report['synthetic_query_bytes']} synthetic bytes**; no cloud charges/model calls.
- Current-process closure baseline and reviewer time: **unknown / not measured**. No production improvement is claimed.

## JavaScript controller/render check

```json
{ui}
```

This checks all four main views and all nine seeded detail render paths, escaped user text, search, controller form callbacks, the full live-API workflow, reload, export and replay. It uses minimal DOM stubs, not a browser engine.

## Remaining limitations

- **Browser visual, layout, keyboard and accessibility testing remains unverified.** Chromium was unavailable in the build environment; its download failed. No screenshot or browser-pass claim is made.
- The held-out fixtures were partitioned before evaluation; they are synthetic rule regression checks, not blinded independent validation or a real-world performance estimate.
- No production connectors, enterprise identity, raw-row cohort validation, causal/statistical inference, automatic scheduler, distributed lease service or live work pilot were tested.
- Cohort composition shifts are explicitly supplied by the fixture; automated stratified detection is a work integration task.
- SQLite transactions support this local single-process workload. Content hashes detect inconsistency but do not establish a tamper-proof audit trail.
- Denied adapter calls are saved as denied measurement receipts and cannot close. Malformed HTTP commands are rejected without being appended to the successful-command state history.

See APP_SPEC.md for implementation decisions and docs/WORK_HANDOFF.md for work integration.
'''
    (ROOT/'docs/VERIFICATION_REPORT.md').write_text(content)
    print(f'{count} Python tests passed; 56 fixtures passed; clean deterministic demo passed; JavaScript smoke '+('passed' if shutil.which('node') else 'skipped')+'.')
    print('Report: docs/VERIFICATION_REPORT.md')


if __name__=='__main__':main()
